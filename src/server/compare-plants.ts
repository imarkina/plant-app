import { z } from 'zod';
import { client } from './client';
import { type PlantComparisonSchema, plantComparisonSchema } from './compare-plants.schema';

const prompt =
  'Ты — опытный ботаник и фитопатолог. Я отправляю тебе два изображения одного и того же растения в разные моменты времени (Первое фото и Второе фото), а также информацию о предыдущих диагнозах/уходе.\n' +
  '\n' +
  'Твоя задача — проанализировать динамику изменений и дать четкую оценку эффективности ухода.\n' +
  '\n' +
  '---\n' +
  'Контекст:\n' +
  '• Даты фото\n' +
  '• Предыдущий диагноз / проведенное лечение\n' +
  '---\n' +
  '\n' +
  'Сформируй ответ строго по следующей структуре:\n' +
  '\n' +
  '1. 📊 Главный вывод (Динамика состояния) — ПОМЕСТИ ЭТО В САМЫЙ ВЕРХ ОТВЕТА\n' +
  'Напиши краткий вердикт (2–3 предложения), отражающий суть изменений.\n' +
  'Примеры формата:\n' +
  '— «За две недели появились новые здоровые листья, тургор полностью восстановился — выбранный уход работает отлично, продолжай в том же духе!»\n' +
  '— «За прошедший месяц признаки перелива усилились, пожелтение прогрессирует — срочно прекрати полив и проверь корни на гниль.»\n' +
  '— «Динамика нейтральная: распространение болезни остановилось, но признаков нового роста пока нет — требуется еще время.»\n' +
  '\n' +
  '2. 🔍 Подробный сравнительный анализ\n' +
  'Сравни два фото и опиши конкретные изменения:\n' +
  '— Листья и побеги: (появление новых приростов, изменение цвета, тургора, увядание или отмирание старых).\n' +
  '— Проблемные зоны: (уменьшились или увеличились пятна, налет, следы вредителей, повреждения).\n' +
  '— Общий габитус и вид: (стало ли растение более пышным, вытянулось ли, наклонилось и т.д.).\n' +
  '\n' +
  '3. 🎯 Корректировка плана ухода\n' +
  '— Что ОСТАВИТЬ без изменений (какие действия доказали свою эффективность).\n' +
  '— Что СРОЧНО ИЗМЕНИТЬ или СКОРРЕКТИРОВАТЬ (изменение графика полива, освещения, обработка, отмена/введение удобрений).\n' +
  '— На что обратить внимание в ближайшие 1-2 недели (контрольные точки наблюдения).\n' +
  '\n' +
  'Пиши четко, структурировано, простым и понятным языком, без лишней "воды".';

export const comparePlants = async ({
  base64First,
  base64Last,
  analysisFirst,
  analysisLast,
  mimeType,
}: {
  base64First: string;
  base64Last: string;
  analysisFirst: string;
  analysisLast: string;
  mimeType: string;
}): Promise<PlantComparisonSchema | undefined> => {
  const response = await client.models.generateContent({
    model: 'gemini-3.6-flash',
    contents: [
      { text: 'Фото и диагноз РАНЕЕ (было):' },
      { inlineData: { mimeType, data: base64First } },
      { text: `Диагноз ранее: ${JSON.stringify(analysisFirst)}` },

      { text: 'Фото и диагноз СЕЙЧАС (стало):' },
      { inlineData: { mimeType, data: base64Last } },
      { text: `Диагноз сейчас: ${JSON.stringify(analysisLast)}` },

      { text: prompt },
    ],
    config: {
      responseMimeType: 'application/json',
      responseJsonSchema: z.toJSONSchema(plantComparisonSchema),
    },
  });

  if (response && response.text) {
    const raw: unknown = JSON.parse(response.text);

    return plantComparisonSchema.parse(raw);
  }
};
